// Writes the resolved release dependency graph of :app in the gradle.lockfile format that
// OSV-Scanner reads, plus the list of modules our own projects declare directly.
// Used by tools/osv/scan.py; see docs/BUILD.md ("Dependency vulnerability check").
//
//   ./gradlew -I tools/osv/resolved-deps.init.gradle.kts :app:osvLockfile
//
// An init script keeps this out of the normal build: nothing changes for assemble or test.

import org.gradle.api.artifacts.component.ModuleComponentIdentifier
import org.gradle.api.artifacts.component.ProjectComponentIdentifier
import org.gradle.api.artifacts.result.ResolvedComponentResult
import org.gradle.api.artifacts.result.ResolvedDependencyResult

gradle.projectsEvaluated {
    val root = rootProject
    val app = root.project(":app")
    val configurationName = "releaseRuntimeClasspath"
    val graph = app.configurations.getByName(configurationName).incoming.resolutionResult.rootComponent
    val lockfile = root.layout.buildDirectory.file("osv/gradle.lockfile")
    val directFile = root.layout.buildDirectory.file("osv/direct.txt")

    // Registered on :app because only a task of the owning project may resolve its configuration.
    app.tasks.register("osvLockfile") {
        group = "verification"
        description = "Writes build/osv/gradle.lockfile and build/osv/direct.txt for OSV-Scanner."
        outputs.files(lockfile, directFile)
        outputs.upToDateWhen { false }
        doLast {
            val all = sortedSetOf<String>()
            val direct = sortedSetOf<String>()
            val seen = mutableSetOf<ResolvedComponentResult>()

            fun coordinates(component: ResolvedComponentResult): String? =
                (component.id as? ModuleComponentIdentifier)?.let { "${it.group}:${it.module}:${it.version}" }

            // fromOurs: the edge starts at the app or one of our library projects, so it is a declared dependency.
            fun walk(component: ResolvedComponentResult, fromOurs: Boolean) {
                coordinates(component)?.let { all += it; if (fromOurs) direct += it }
                if (!seen.add(component)) return
                val ours = component.id is ProjectComponentIdentifier
                component.dependencies.filterIsInstance<ResolvedDependencyResult>().forEach { edge ->
                    walk(edge.selected, ours)
                }
            }
            walk(graph.get(), fromOurs = false)

            val lock = lockfile.get().asFile
            lock.parentFile.mkdirs()
            lock.writeText(
                buildString {
                    appendLine("# Resolved :app:$configurationName, generated by tools/osv/resolved-deps.init.gradle.kts")
                    all.forEach { appendLine("$it=$configurationName") }
                    appendLine("empty=")
                },
            )
            directFile.get().asFile.writeText(direct.joinToString("\n", postfix = "\n"))
            logger.lifecycle("osvLockfile: ${all.size} modules, ${direct.size} declared directly -> ${lock.path}")
        }
    }
}
